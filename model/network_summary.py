"""Model-only CPU export statistics and Markdown; no firmware artifacts needed."""
from collections import Counter
from math import prod


# Serialized ExecuTorch scalar types used by this export path.
_SCALARS = {
    0: ("uint8", 1), 1: ("int8", 1), 2: ("int16", 2),
    3: ("int32", 4), 4: ("int64", 8), 5: ("float16", 2),
    6: ("float32", 4), 7: ("float64", 8), 11: ("bool", 1),
    15: ("bfloat16", 2),
}


def _tensor(value):
    return hasattr(value, "scalar_type") and hasattr(value, "sizes")


def _tensor_bytes(value):
    if not _tensor(value):
        return 0
    scalar = int(value.scalar_type)
    if scalar not in _SCALARS:
        raise ValueError(f"Unsupported summary tensor scalar type: {scalar}")
    return prod(value.sizes) * _SCALARS[scalar][1]


def collect_network_stats(program, source_model):
    """Summarize the single-forward CPU program emitted by export_cpu.py."""
    if len(program.execution_plan) != 1:
        raise ValueError("Network summary currently requires one execution plan")
    plan = program.execution_plan[0]
    counts = Counter()
    layers = []
    weights, biases = {}, {}
    macs = 0
    for chain in plan.chains:
        for instruction in chain.instructions:
            call = instruction.instr_args
            if not hasattr(call, "op_index"):
                continue
            op = plan.operators[call.op_index]
            counts[op.name] += 1
            output = plan.values[call.args[-1]].val
            layers.append(dict(
                operator=op.name,
                output_shape=list(output.sizes) if _tensor(output) else None,
                output_dtype=_SCALARS.get(int(output.scalar_type), ("unknown", 0))[0] if _tensor(output) else None,
                dim_order=list(output.dim_order) if _tensor(output) else None,
            ))
            if op.name in ("cortex_m::quantized_conv2d", "cortex_m::quantized_linear"):
                weight = plan.values[call.args[1]].val
                bias = plan.values[call.args[2]].val
                # Count shared constants once, even when multiple calls use them.
                weights[call.args[1]] = _tensor_bytes(weight)
                if _tensor(bias):
                    biases[call.args[2]] = _tensor_bytes(bias)
                if op.name == "cortex_m::quantized_conv2d":
                    # Compiled convolution weights are OHWI.
                    macs += prod(output.sizes) * prod(weight.sizes[1:])
                else:
                    macs += prod(output.sizes) * weight.sizes[-1]
    parameters = list(source_model.parameters())
    buffers = [dict(id=i, bytes=size) for i, size in enumerate(plan.non_const_buffer_sizes) if i > 0]
    return dict(
        source_parameter_elements=sum(p.numel() for p in parameters),
        source_parameter_bytes=sum(p.numel() * p.element_size() for p in parameters),
        planned_tensor_bytes=sum(b["bytes"] for b in buffers),
        planned_buffers=buffers,
        constant_buffer_bytes=sum(len(b.storage) for b in program.constant_buffer),
        referenced_conv_linear_weight_bytes=sum(weights.values()),
        referenced_conv_linear_bias_bytes=sum(biases.values()),
        conv_linear_macs=macs,
        operators=dict(sorted(counts.items())),
        operator_invocations=sum(counts.values()),
        layers=layers,
    )


def _cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def _size_row(label, size, meaning):
    return f"| {label} | {size:,} | {size / 1024:,.2f} | {meaning} |"


def render_network_summary(report, stats, model_artifact):
    """Generate a reproducible model-only report, using freshly exported data."""
    if report["planned_tensor_bytes"] != stats["planned_tensor_bytes"]:
        raise ValueError("Report and serialized memory plan disagree")
    name = _cell(report["model"]["name"])
    pte_bytes = report["pte_bytes"]
    constants = stats["constant_buffer_bytes"]
    labels = report["model"]["labels"]
    lines = [
        "# CPU model compilation network summary", "",
        "<!-- Generated by model/export_cpu.py; do not edit by hand. -->", "",
        f"**Model:** {name}. **CPU:** `{report['cpu']}`. **ISA:** `{report['isa']}`.",
        f"**ExecuTorch:** `{report['executorch']}`. Input/output: **signed INT8**.", "",
        "This report is regenerated by each successful CPU model export. It uses",
        "the current serialized program and source model only; no firmware build,",
        "ELF, linker map or board connection is required. The latest exported model",
        "replaces the previous contents of this shared report.", "",
        "## Model RAM and storage requirements", "",
        "| Measurement | Bytes | KiB | Meaning |",
        "|---|---:|---:|---|",
        _size_row("**Planned model RAM**", stats["planned_tensor_bytes"], "Non-constant tensor buffers, including planned kernel scratch and layout-copy buffers"),
        _size_row("**Model storage payload (.pte)**", pte_bytes, "Storage required for the serialized model; use this payload size if storing the model in off-chip flash"),
        _size_row("All deserialized constant buffers", constants, "Included in the .pte; not an additional storage requirement"),
        _size_row("Referenced convolution/linear weights", stats["referenced_conv_linear_weight_bytes"], "Tensor payloads, deduplicated by serialized value; included in the model"),
        _size_row("Referenced convolution/linear biases", stats["referenced_conv_linear_bias_bytes"], "Tensor payloads, included in the model"), "",
        "**Total firmware SRAM usage: not determined by model export.** The planned",
        "model RAM excludes runtime/method metadata, stack, heap, unplanned temporary",
        "allocations, external image buffers and other program data. Input/output",
        "sizes below must not be added again when their storage is already planned.", "",
        "**Actual off-chip flash usage: not assigned by model export.** The .pte",
        "payload is the model storage requirement if placed there. Runtime/kernel",
        "code, alignment, partitions and other assets require additional storage.",
        "No assumption is made about placing tensors in SRAM, TCM or DDR, or about",
        "reading model constants in place versus copying them into RAM.", "",
        "These are model-level compilation requirements, not physical-board memory",
        "measurements. Planned RAM is a static allocation plan, not a measured",
        "runtime high-water mark. 1 KiB = 1,024 bytes.", "",
        "### Planned non-constant buffers", "",
        "| Buffer ID | Bytes | KiB |", "|---|---:|---:|",
    ]
    for buffer in stats["planned_buffers"]:
        lines.append(f"| {buffer['id']} | {buffer['bytes']:,} | {buffer['bytes'] / 1024:,.2f} |")
    lines += ["", "## Network and tensor interface", "",
              "| Property | Value |", "|---|---|"]
    for label, value in [
        ("Source parameter elements", f"{stats['source_parameter_elements']:,}"),
        ("Source parameter tensor bytes", f"{stats['source_parameter_bytes']:,}; before export quantization, excluding checkpoint-container overhead"),
        ("Output class order", ", ".join(_cell(x) for x in labels)),
        ("Compiled operator invocations", stats["operator_invocations"]),
        ("Convolution/linear MACs per inference", f"{stats['conv_linear_macs']:,}"),
    ]:
        lines.append(f"| {label} | {value} |")
    lines += ["", "MACs count standard compiled convolution and linear work only. They exclude",
              "pooling, copies, concatenation and preprocessing, and are not latency or",
              "cycle estimates. Biases, accumulators and shape data may use wider integers.", "",
              "| Tensor | Logical shape | Dtype | Physical storage | Scale | Zero point |",
              "|---|---|---|---|---:|---:|"]
    for key in ("input", "output"):
        tensor = report[key]
        lines.append(f"| {key.capitalize()} | `{tensor['shape']}` | `{tensor['dtype']}` | {_cell(tensor.get('storage', 'Default contiguous'))} | {tensor['scale']:.10g} | {tensor['zero_point']} |")
    lines += ["", "Quantization: `q = clamp(round(real / scale) + zero_point, -128, 127)`.",
              "Decode scores as `real = (q - zero_point) * scale`.",
              "The input real values must follow the model's preprocessing; raw RGB",
              "bytes are not themselves normalized INT8 model inputs.", "",
              "## Compiled operators", "",
              "| Operator | Invocations |", "|---|---:|"]
    for op, count in stats["operators"].items():
        lines.append(f"| `{op}` | {count} |")
    lines += ["", "## Compiled network sequence", "",
              "Shapes are logical tensor shapes; dimension order describes physical storage.", "",
              "| Step | Operation | Output shape | Dtype | Dimension order |",
              "|---|---|---|---|---|"]
    for i, layer in enumerate(stats["layers"], 1):
        lines.append(f"| {i} | `{layer['operator']}` | `{layer['output_shape']}` | `{layer['output_dtype']}` | `{layer['dim_order']}` |")
    lines += ["", "## Host validation", "",
              f"- Calibration samples: {report['calibration_samples']}.",
              f"- Reference cases: {len(report['expected'])}.",
              "- INT8 boundary conversion preserved the original quantized host reference outputs exactly.",
              "- Serialized INT8 input/output and portable-kernel layout checks passed.",
              f"- Maximum FP32 versus dequantized INT8 absolute output error: {report['max_quantization_error']:.7g} (real score units).",
              f"- Configured runtime comparison tolerance: {report['tolerance']} INT8 codes; this export does not execute firmware.", "",
              "| Case | FP32 predicted class | INT8 predicted class |", "|---|---|---|"]
    for i, (fp32, integer) in enumerate(zip(report["float_reference"], report["expected"])):
        fp_class = labels[max(range(len(fp32)), key=lambda j: fp32[j])]
        int_class = labels[max(range(len(integer)), key=lambda j: integer[j])]
        lines.append(f"| {i} | {_cell(fp_class)} | {_cell(int_class)} |")
    warning = report["model"].get("calibration_warning")
    lines += ["", warning or "Calibration/reference samples verify the demonstrated export path; an independent validation dataset is needed to assess accuracy.",
              "", "No firmware execution result or measured accuracy, latency or RAM peak is inferred from these host checks.",
              "", "## Artifacts and provenance", "",
              f"- Serialized model: [`{model_artifact}`](../{model_artifact}).",
              f"- Detailed quantization report: [`validation.json`](../{model_artifact.rsplit('/', 1)[0]}/validation.json).",
              f"- Lowered graph: [`graph.txt`](../{model_artifact.rsplit('/', 1)[0]}/graph.txt).",
              "- Generated by `model/export_cpu.py` and `model/network_summary.py`."]
    if report["model"].get("checkpoint_sha256"):
        lines.append(f"- Checkpoint SHA-256: `{report['model']['checkpoint_sha256']}`.")
    return "\n".join(lines) + "\n"
